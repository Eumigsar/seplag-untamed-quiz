export function getMoveById(id: string): CombatMove | undefined {
  return COMBAT_MOVES.find(m => m.id === id);
}

export function getEnemyById(id: string): Enemy | undefined {
  return ENEMIES.find(e => e.id === id);
}

export function getAvailableMoves(hskLevel: number): CombatMove[] {
  return COMBAT_MOVES.filter(m => m.unlocksAtHsk <= hskLevel);
}
